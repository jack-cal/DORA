"""Authenticated v1 single-key and v2 BIP32/BIP39 P2WPKH wallet files.

Keys are generated by the OS-backed secrets module. Encryption uses cryptography
AES-256-GCM and OpenSSL-backed hashlib.scrypt; no cipher or signing primitive is
implemented here. The encrypted envelope binds network, genesis, key type and
public key through authenticated metadata. V1 keys and ciphertext are retained
without conversion. V2 encrypts 256-bit BIP39 entropy and binds the SUMUWW-specific
derivation namespace/path. This module does not integrate hardware wallets.
Python does not guarantee erasure of unlocked secrets from process memory.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
import os
from pathlib import Path
import secrets
import tempfile

from coincurve import PrivateKey
from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from .address import encode_address
from .profiles import SUMUWW, NetworkProfile, REGTEST, get_network
from .primitives import hash_to_display
from .wallet import SECP256K1_ORDER, p2wpkh_script
from .hd import (SUMUWW_NAMESPACE, HARDENED, HDKeyError, HDNode,
                 entropy_to_mnemonic, mnemonic_to_entropy, mnemonic_to_seed)

MAX_WALLET_BYTES = 4096
MAX_PASSWORD_BYTES = 1024
SCRYPT_N = 1 << 17
SCRYPT_R = 8
SCRYPT_P = 1
SCRYPT_DKLEN = 32
SCRYPT_MAXMEM = 256 * 1024 * 1024
_FORMAT = "sumuww-single-key-wallet"
_KEY_TYPE = "secp256k1-p2wpkh"
_ROOT_FIELDS = {"format", "version", "network", "profile", "genesis_hash", "address_hrp", "key_type", "witness_version", "public_key", "kdf", "cipher"}
_KDF_FIELDS = {"name", "n", "r", "p", "dklen", "salt"}
_CIPHER_FIELDS = {"name", "nonce", "ciphertext"}
_HD_FORMAT = "sumuww-hd-wallet"
_HD_ROOT_FIELDS = _ROOT_FIELDS | {"hd"}
_HD_ACCOUNTS = {"dora": 0, "regtest": 1, "retarget-lab": 2}


class WalletError(ValueError):
    """Safe-to-display error without passwords or decrypted secret values."""


class WalletFormatError(WalletError):
    """The bounded wallet envelope is malformed or has the wrong profile."""


class WalletAuthenticationError(WalletError):
    """The password or authenticated encrypted wallet contents do not match."""


@dataclass(frozen=True, repr=False)
class WalletKey:
    _private_key: PrivateKey = field(repr=False)
    network: NetworkProfile = field(default=REGTEST, repr=False)

    def __post_init__(self):
        # Preserve WalletKey(PrivateKey(...)) for existing regtest callers, but
        # never let a custom, unregistered profile change address semantics.
        registered = get_network(self.network)
        object.__setattr__(self, "network", registered)

    @property
    def pubkey(self) -> bytes:
        return self._private_key.public_key.format(compressed=True)

    @property
    def script_pubkey(self) -> bytes:
        return p2wpkh_script(self.pubkey)

    @property
    def address(self) -> str:
        return encode_address(self.script_pubkey, network=self.network)

    def sign_digest(self, digest: bytes) -> bytes:
        if not isinstance(digest, bytes) or len(digest) != 32:
            raise WalletError("signature digest must be exactly 32 bytes")
        return self._private_key.sign(digest, hasher=None)

    def __repr__(self) -> str:
        return f"WalletKey(address={self.address!r})"

    @property
    def is_hd(self) -> bool:
        return False

    @property
    def wallet_version(self) -> int:
        return 1


def _hd_metadata(profile):
    account = _HD_ACCOUNTS[profile.name]
    return {"scheme": "BIP32-BIP39", "wordlist": "english", "entropy_bits": 256,
            "namespace": SUMUWW_NAMESPACE, "account": account, "passphrase": False,
            "path": f"m/{SUMUWW_NAMESPACE}'/{account}'/0/0"}


def _hd_account_node(entropy, profile):
    if type(entropy) is not bytes or len(entropy) != 32:
        raise WalletFormatError("HD wallet entropy must contain exactly 32 bytes")
    phrase = entropy_to_mnemonic(entropy)
    master = HDNode.from_seed(mnemonic_to_seed(phrase))
    account = _HD_ACCOUNTS[profile.name]
    return master.derive_path(f"m/{SUMUWW_NAMESPACE}'/{account}'", skip_invalid=False)


@dataclass(frozen=True, repr=False)
class HDWalletKey(WalletKey):
    """First receive key plus a private derivation root; repr never emits seed."""
    _entropy: bytes = field(default=b"", repr=False)
    _account_node: HDNode = field(init=False, repr=False, compare=False)

    def __post_init__(self):
        super().__post_init__()
        try:
            account = _hd_account_node(self._entropy, self.network)
            first = account.derive_child(0, skip_invalid=False).derive_child(0, skip_invalid=False)
        except HDKeyError:
            raise WalletFormatError("HD wallet derivation is invalid") from None
        if self.pubkey != first.pubkey:
            raise WalletFormatError("HD wallet first key does not match its derivation")
        object.__setattr__(self, "_account_node", account)

    @property
    def is_hd(self) -> bool:
        return True

    @property
    def wallet_version(self) -> int:
        return 2

    @property
    def derivation_path(self) -> str:
        return _hd_metadata(self.network)["path"]

    def child(self, index: int, *, change: bool = False) -> WalletKey:
        if type(index) is not int or not 0 <= index < HARDENED:
            raise WalletError("HD receive index must be between 0 and 2147483647")
        if type(change) is not bool:
            raise WalletError("HD change selection must be boolean")
        try:
            node = self._account_node.derive_child(int(change), skip_invalid=False)
            leaf = node.derive_child(index, skip_invalid=False)
        except HDKeyError:
            raise WalletError("HD child derivation is invalid") from None
        return WalletKey(leaf._private_key, self.network)

    derive = child

    def __repr__(self) -> str:
        return f"HDWalletKey(address={self.address!r}, wallet_version=2)"


def _hd_key_from_entropy(entropy, profile):
    try:
        account = _hd_account_node(entropy, profile)
        first = account.derive_child(0, skip_invalid=False).derive_child(0, skip_invalid=False)
        return HDWalletKey(first._private_key, profile, entropy)
    except HDKeyError:
        raise WalletFormatError("HD wallet derivation is invalid") from None


def _password_bytes(password: str, *, creating: bool) -> bytes:
    if not isinstance(password, str):
        raise WalletError("wallet password must be text")
    if not 1 <= len(password) <= MAX_PASSWORD_BYTES:
        raise WalletError("wallet password must contain 1 to 1024 UTF-8 bytes")
    try:
        raw = password.encode("utf-8")
    except UnicodeError:
        raise WalletError("wallet password must be valid UTF-8 text") from None
    if not raw or len(raw) > MAX_PASSWORD_BYTES:
        raise WalletError("wallet password must contain 1 to 1024 UTF-8 bytes")
    if creating and len(password) < 12:
        raise WalletError("new wallet password must contain at least 12 characters")
    return raw


def _derive_key(password: bytes, salt: bytes) -> bytes:
    return hashlib.scrypt(password, salt=salt, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P, dklen=SCRYPT_DKLEN, maxmem=SCRYPT_MAXMEM)


def _canonical_json(value: dict) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")


def _aad(envelope: dict) -> bytes:
    metadata = dict(envelope)
    metadata["cipher"] = {name: value for name, value in envelope["cipher"].items() if name != "ciphertext"}
    return _canonical_json(metadata)


def _hex_bytes(value, length: int) -> bytes:
    if not isinstance(value, str) or len(value) != 2 * length or any(character not in "0123456789abcdef" for character in value):
        raise WalletFormatError("wallet contains an invalid binary field")
    return bytes.fromhex(value)


def _unique_object(pairs):
    result = {}
    for name, value in pairs:
        if name in result:
            raise WalletFormatError("wallet contains duplicate JSON fields")
        result[name] = value
    return result


def _wallet_identity(profile, is_hd, *, legacy=False):
    public = profile is SUMUWW
    return {"format": ("dora-hd-wallet" if is_hd else "dora-single-key-wallet")
            if legacy else (_HD_FORMAT if is_hd else _FORMAT),
            "version": 2 if is_hd else 1,
            "network": "sumuww" if public and not legacy else profile.name,
            "profile": "sumuww-independent-v0.12-p2wpkh" if public and not legacy else profile.profile_id,
            "genesis_hash": hash_to_display(profile.genesis.block_hash()),
            "address_hrp": "dora" if public and legacy else profile.address_hrp,
            "key_type": _KEY_TYPE, "witness_version": 0}


def _parse_envelope(raw: bytes, *, network="regtest") -> dict:
    profile = get_network(network)
    if not isinstance(raw, bytes) or not 1 <= len(raw) <= MAX_WALLET_BYTES:
        raise WalletFormatError("wallet file must contain 1 to 4096 bytes")
    try:
        envelope = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique_object)
    except (UnicodeError, ValueError, RecursionError):
        raise WalletFormatError("wallet file must contain valid UTF-8 JSON") from None
    is_hd = (type(envelope) is dict and type(envelope.get("version")) is int
             and envelope.get("version") == 2)
    fields = _HD_ROOT_FIELDS if is_hd else _ROOT_FIELDS
    if type(envelope) is not dict or set(envelope) != fields:
        raise WalletFormatError("wallet fields do not match the supported schema")
    identities = (_wallet_identity(profile, is_hd), _wallet_identity(profile, is_hd, legacy=True))
    if not any(all(type(envelope[name]) is type(value) and envelope[name] == value
                   for name, value in identity.items()) for identity in identities):
        raise WalletFormatError("wallet version, network or key type is unsupported")
    if is_hd:
        hd = envelope["hd"]
        expected_hd = _hd_metadata(profile)
        if type(hd) is not dict or set(hd) != set(expected_hd):
            raise WalletFormatError("HD wallet metadata does not match the supported schema")
        if any(type(hd[name]) is not type(value) or hd[name] != value
               for name, value in expected_hd.items()):
            raise WalletFormatError("HD wallet derivation metadata is unsupported")
    kdf = envelope["kdf"]
    if type(kdf) is not dict or set(kdf) != _KDF_FIELDS:
        raise WalletFormatError("wallet KDF fields do not match the supported schema")
    for name, value in {"name": "scrypt", "n": SCRYPT_N, "r": SCRYPT_R, "p": SCRYPT_P, "dklen": SCRYPT_DKLEN}.items():
        if type(kdf[name]) is not type(value) or kdf[name] != value:
            raise WalletFormatError("wallet KDF parameters are unsupported")
    cipher = envelope["cipher"]
    if type(cipher) is not dict or set(cipher) != _CIPHER_FIELDS or cipher["name"] != "AES-256-GCM":
        raise WalletFormatError("wallet cipher fields do not match the supported schema")
    _hex_bytes(kdf["salt"], 16)
    _hex_bytes(cipher["nonce"], 12)
    _hex_bytes(cipher["ciphertext"], 48)
    public_key = _hex_bytes(envelope["public_key"], 33)
    try:
        p2wpkh_script(public_key)
    except ValueError:
        raise WalletFormatError("wallet public key is invalid") from None
    if public_key[0] not in (2, 3):
        raise WalletFormatError("wallet public key must be compressed")
    return envelope


def _unlock(raw: bytes, password: bytes, *, network="regtest") -> WalletKey:
    profile = get_network(network)
    envelope = _parse_envelope(raw, network=profile)
    encryption_key = _derive_key(password, _hex_bytes(envelope["kdf"]["salt"], 16))
    try:
        secret = AESGCM(encryption_key).decrypt(_hex_bytes(envelope["cipher"]["nonce"], 12), _hex_bytes(envelope["cipher"]["ciphertext"], 48), _aad(envelope))
    except InvalidTag:
        raise WalletAuthenticationError("wallet password or encrypted contents do not match") from None
    try:
        key = (_hd_key_from_entropy(secret, profile) if envelope["version"] == 2
               else WalletKey(PrivateKey(secret), profile))
    except ValueError:
        raise WalletFormatError("wallet encrypted key material is invalid") from None
    if len(secret) != 32 or key.pubkey.hex() != envelope["public_key"]:
        raise WalletFormatError("wallet encrypted key does not match its public key")
    return key


def _read_wallet(path: str | Path) -> bytes:
    with Path(path).open("rb") as source:
        raw = source.read(MAX_WALLET_BYTES + 1)
    if not 1 <= len(raw) <= MAX_WALLET_BYTES:
        raise WalletFormatError("wallet file must contain 1 to 4096 bytes")
    return raw


def _publish_no_replace(temporary: Path, destination: Path) -> None:
    # Windows rename fails if the destination exists, and works without hard
    # links on FAT32/exFAT. POSIX rename would replace an existing file, so keep
    # exclusive hard-link publication there instead.
    if os.name == "nt":
        os.rename(temporary, destination)
    else:
        os.link(temporary, destination)


def _publish_exclusively(path: str | Path, raw: bytes) -> None:
    """Publish a fully written encrypted file without replacing an existing path.

    A same-directory, no-replace rename on Windows avoids requiring hard links
    on removable filesystems. Other platforms retain exclusive hard linking.
    The complete encrypted file is flushed, fsynced and closed first. Filesystem
    ACLs, where supported, are inherited from the destination directory; this
    does not promise power-loss durability.
    """
    destination = Path(path)
    if os.path.lexists(destination):
        raise WalletError("wallet destination already exists")
    destination.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=".sumuww-wallet-", suffix=".tmp", dir=destination.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as output:
            descriptor = -1
            if output.write(raw) != len(raw):
                raise OSError("wallet file write was incomplete")
            output.flush()
            os.fsync(output.fileno())
        try:
            _publish_no_replace(temporary, destination)
        except FileExistsError:
            raise WalletError("wallet destination already exists") from None
    finally:
        try:
            if descriptor != -1:
                os.close(descriptor)
        finally:
            temporary.unlink(missing_ok=True)


def create_wallet(path: str | Path, password: str, *, network="regtest") -> WalletKey:
    """Generate one random key and save only its authenticated encrypted form."""
    profile = get_network(network)
    password_raw = _password_bytes(password, creating=True)
    if os.path.lexists(path):
        raise WalletError("wallet destination already exists")
    scalar = secrets.randbelow(SECP256K1_ORDER - 1) + 1
    secret = scalar.to_bytes(32, "big")
    key = WalletKey(PrivateKey(secret), profile)
    salt = secrets.token_bytes(16)
    nonce = secrets.token_bytes(12)
    envelope = {**_wallet_identity(profile, False), "public_key": key.pubkey.hex(), "kdf": {"name": "scrypt", "n": SCRYPT_N, "r": SCRYPT_R, "p": SCRYPT_P, "dklen": SCRYPT_DKLEN, "salt": salt.hex()}, "cipher": {"name": "AES-256-GCM", "nonce": nonce.hex()}}
    envelope["cipher"]["ciphertext"] = AESGCM(_derive_key(password_raw, salt)).encrypt(nonce, secret, _aad(envelope)).hex()
    _publish_exclusively(path, _canonical_json(envelope) + b"\n")
    return key


def _write_hd_wallet(path, password_raw, entropy, profile):
    key = _hd_key_from_entropy(entropy, profile)
    salt = secrets.token_bytes(16)
    nonce = secrets.token_bytes(12)
    envelope = {**_wallet_identity(profile, True),
                "public_key": key.pubkey.hex(), "hd": _hd_metadata(profile),
                "kdf": {"name": "scrypt", "n": SCRYPT_N, "r": SCRYPT_R, "p": SCRYPT_P,
                        "dklen": SCRYPT_DKLEN, "salt": salt.hex()},
                "cipher": {"name": "AES-256-GCM", "nonce": nonce.hex()}}
    envelope["cipher"]["ciphertext"] = AESGCM(_derive_key(password_raw, salt)).encrypt(nonce, entropy, _aad(envelope)).hex()
    _publish_exclusively(path, _canonical_json(envelope) + b"\n")
    return key


def create_hd_wallet(path: str | Path, password: str, *, network="regtest") -> HDWalletKey:
    """Create encrypted v2. Never return mnemonic words implicitly or log them."""
    profile = get_network(network)
    password_raw = _password_bytes(password, creating=True)
    if os.path.lexists(path):
        raise WalletError("wallet destination already exists")
    return _write_hd_wallet(path, password_raw, secrets.token_bytes(32), profile)


def recover_hd_wallet(path: str | Path, password: str, mnemonic: str, *,
                      network="regtest", passphrase="") -> HDWalletKey:
    """Explicit 24-word restore; wallet-file password is unrelated to the seed."""
    profile = get_network(network)
    password_raw = _password_bytes(password, creating=True)
    if os.path.lexists(path):
        raise WalletError("wallet destination already exists")
    if type(passphrase) is not str or passphrase != "":
        raise WalletError("HD wallet v2 uses recovery words without an additional passphrase")
    try:
        entropy = mnemonic_to_entropy(mnemonic)
    except HDKeyError:
        raise WalletFormatError("HD recovery requires valid English BIP39 words and checksum") from None
    if len(entropy) != 32:
        raise WalletFormatError("HD recovery requires exactly 24 English BIP39 words")
    return _write_hd_wallet(path, password_raw, entropy, profile)


def export_mnemonic(path: str | Path, password: str, *, network="regtest",
                    expected_script: bytes | None = None) -> str:
    """Explicit password-reauthenticated secret export, never a status field."""
    if expected_script is not None and (type(expected_script) is not bytes
            or len(expected_script) != 22 or expected_script[:2] != b"\x00\x14"):
        raise WalletError("Expected wallet script must be native P2WPKH")
    # Authenticate exactly one file snapshot. The caller's selected public
    # identity is compared to that same decrypted key before any secret export,
    # rather than checking one file read and exporting from a second read.
    key = load_wallet(path, password, network=network)
    if expected_script is not None and key.script_pubkey != expected_script:
        raise WalletError("The wallet file has changed since it was opened")
    if not isinstance(key, HDWalletKey):
        raise WalletError("This single-key wallet has no recovery words; back up its encrypted file")
    return entropy_to_mnemonic(key._entropy)


# Clear explicit names for GUI integration. All require password re-entry.
export_seed = export_mnemonic
export_hd_mnemonic = export_mnemonic


def load_wallet(path: str | Path, password: str, *, network="regtest") -> WalletKey:
    profile = get_network(network)
    password_raw = _password_bytes(password, creating=False)
    return _unlock(_read_wallet(path), password_raw, network=profile)


def backup_wallet(source: str | Path, destination: str | Path, password: str, *,
                  network="regtest", expected_script: bytes | None = None) -> WalletKey:
    """Verify the password and envelope before copying the unchanged ciphertext."""
    profile = get_network(network)
    password_raw = _password_bytes(password, creating=False)
    if expected_script is not None and (type(expected_script) is not bytes
            or len(expected_script) != 22 or expected_script[:2] != b"\x00\x14"):
        raise WalletError("Expected wallet script must be native P2WPKH")
    raw = _read_wallet(source)
    key = _unlock(raw, password_raw, network=profile)
    if expected_script is not None and key.script_pubkey != expected_script:
        raise WalletError("The wallet file has changed since it was opened")
    _publish_exclusively(destination, raw)
    return key


def restore_wallet(backup: str | Path, destination: str | Path, password: str, *, network="regtest") -> WalletKey:
    return backup_wallet(backup, destination, password, network=network)
